CREATE OR REPLACE FUNCTION public.log_activity()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_actor_email text := auth.jwt() ->> 'email';
  v_old_row jsonb;
  v_new_row jsonb;
  v_changes jsonb := '{}'::jsonb;
  v_key text;
  v_old_value jsonb;
  v_new_value jsonb;
  v_record_id text;
  v_summary text;
BEGIN
  IF v_actor_email IS NULL THEN
    IF TG_OP = 'DELETE' THEN
      RETURN OLD;
    END IF;
    RETURN NEW;
  END IF;

  IF TG_OP = 'INSERT' THEN
    v_new_row := to_jsonb(NEW);
    v_record_id := coalesce(v_new_row ->> 'id', v_new_row ->> 'key');
    v_summary := coalesce(v_new_row ->> 'name', v_new_row ->> 'customer_name', v_new_row ->> 'key');
    INSERT INTO public.activity_log (actor_email, action, table_name, record_id, summary, changes)
    VALUES (v_actor_email, 'insert', TG_TABLE_NAME, v_record_id, v_summary, v_new_row - 'fts');
    RETURN NEW;
  ELSIF TG_OP = 'UPDATE' THEN
    v_old_row := to_jsonb(OLD);
    v_new_row := to_jsonb(NEW);
    v_record_id := coalesce(v_new_row ->> 'id', v_new_row ->> 'key');
    v_summary := coalesce(v_new_row ->> 'name', v_new_row ->> 'customer_name', v_new_row ->> 'key');

    FOR v_key, v_new_value IN
      SELECT key, value FROM jsonb_each(v_new_row)
    LOOP
      IF v_key NOT IN ('fts', 'updated_at') THEN
        v_old_value := v_old_row -> v_key;
        IF v_old_value IS DISTINCT FROM v_new_value THEN
          v_changes := v_changes || jsonb_build_object(
            v_key,
            jsonb_build_object('old', v_old_value, 'new', v_new_value)
          );
        END IF;
      END IF;
    END LOOP;

    INSERT INTO public.activity_log (actor_email, action, table_name, record_id, summary, changes)
    VALUES (v_actor_email, 'update', TG_TABLE_NAME, v_record_id, v_summary, v_changes);
    RETURN NEW;
  ELSE
    v_old_row := to_jsonb(OLD);
    v_record_id := coalesce(v_old_row ->> 'id', v_old_row ->> 'key');
    v_summary := coalesce(v_old_row ->> 'name', v_old_row ->> 'customer_name', v_old_row ->> 'key');
    INSERT INTO public.activity_log (actor_email, action, table_name, record_id, summary, changes)
    VALUES (v_actor_email, 'delete', TG_TABLE_NAME, v_record_id, v_summary, v_old_row - 'fts');
    RETURN OLD;
  END IF;
END;
$$;

