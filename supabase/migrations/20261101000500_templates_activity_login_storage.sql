CREATE OR REPLACE FUNCTION public.login_attempt_status(p_email text, p_ip text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_now timestamptz := now();
  v_email_count integer;
  v_ip_count integer;
  v_email_expiry timestamptz;
  v_ip_expiry timestamptz;
  v_locked boolean;
  v_retry_seconds integer;
BEGIN
  SELECT count(*)::integer
  INTO v_email_count
  FROM public.login_events
  WHERE lower(email) = lower(p_email)
    AND success = false
    AND created_at >= v_now - interval '15 minutes';

  SELECT count(*)::integer
  INTO v_ip_count
  FROM public.login_events
  WHERE ip = p_ip
    AND success = false
    AND created_at >= v_now - interval '15 minutes';

  v_locked := v_email_count >= 5 OR v_ip_count >= 20;

  IF v_email_count >= 5 THEN
    SELECT created_at
    INTO v_email_expiry
    FROM public.login_events
    WHERE lower(email) = lower(p_email)
      AND success = false
      AND created_at >= v_now - interval '15 minutes'
    ORDER BY created_at DESC
    OFFSET 4 LIMIT 1;
  END IF;

  IF v_ip_count >= 20 THEN
    SELECT created_at
    INTO v_ip_expiry
    FROM public.login_events
    WHERE ip = p_ip
      AND success = false
      AND created_at >= v_now - interval '15 minutes'
    ORDER BY created_at DESC
    OFFSET 19 LIMIT 1;
  END IF;

  v_retry_seconds := greatest(
    CASE
      WHEN v_email_expiry IS NULL THEN 0
      ELSE ceil(extract(epoch FROM (v_email_expiry + interval '15 minutes' - v_now))::numeric)::integer
    END,
    CASE
      WHEN v_ip_expiry IS NULL THEN 0
      ELSE ceil(extract(epoch FROM (v_ip_expiry + interval '15 minutes' - v_now))::numeric)::integer
    END,
    0
  );

  RETURN jsonb_build_object(
    'locked', v_locked,
    'retry_after_seconds', v_retry_seconds
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.record_login_attempt(
  p_email text,
  p_ip text,
  p_user_agent text,
  p_device_hash text,
  p_success boolean
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_event_count integer;
  v_is_new_device boolean := false;
BEGIN
  SELECT count(*)::integer
  INTO v_event_count
  FROM public.login_events
  WHERE ip = p_ip
    AND created_at >= now() - interval '1 hour';

  IF v_event_count > 200 THEN
    RETURN jsonb_build_object('is_new_device', false);
  END IF;

  IF p_success THEN
    SELECT NOT EXISTS (
      SELECT 1
      FROM public.login_events AS prior
      WHERE lower(prior.email) = lower(p_email)
        AND prior.device_hash IS NOT DISTINCT FROM p_device_hash
        AND prior.success = true
    )
    INTO v_is_new_device;
  END IF;

  INSERT INTO public.login_events (email, ip, user_agent, device_hash, success, is_new_device)
  VALUES (p_email, p_ip, p_user_agent, p_device_hash, p_success, v_is_new_device);

  RETURN jsonb_build_object('is_new_device', v_is_new_device);
END;
$$;

