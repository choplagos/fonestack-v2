ALTER TABLE public.invoices
  ADD COLUMN IF NOT EXISTS items_stock_applied boolean NOT NULL DEFAULT false;

CREATE TABLE IF NOT EXISTS public.invoice_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_id uuid NOT NULL REFERENCES public.invoices (id) ON DELETE CASCADE,
  product_id bigint REFERENCES public.products (id) ON DELETE SET NULL,
  name text NOT NULL,
  brand text,
  spec text,
  imei text,
  quantity integer NOT NULL DEFAULT 1 CHECK (quantity > 0),
  unit_price numeric NOT NULL CHECK (unit_price >= 0),
  unit_cost numeric,
  position integer DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.invoice_items ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.invoice_items TO authenticated;

DROP POLICY IF EXISTS "admins select invoice items" ON public.invoice_items;
CREATE POLICY "admins select invoice items" ON public.invoice_items
  FOR SELECT TO authenticated USING (public.is_admin());
DROP POLICY IF EXISTS "writers insert invoice items" ON public.invoice_items;
CREATE POLICY "writers insert invoice items" ON public.invoice_items
  FOR INSERT TO authenticated WITH CHECK (public.can_write());
DROP POLICY IF EXISTS "writers update invoice items" ON public.invoice_items;
CREATE POLICY "writers update invoice items" ON public.invoice_items
  FOR UPDATE TO authenticated USING (public.can_write()) WITH CHECK (public.can_write());
DROP POLICY IF EXISTS "owners delete invoice items" ON public.invoice_items;
CREATE POLICY "owners delete invoice items" ON public.invoice_items
  FOR DELETE TO authenticated USING (public.is_owner());

CREATE OR REPLACE FUNCTION public.sync_invoice_items_stock(p_invoice_id uuid)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_invoice public.invoices%ROWTYPE;
  v_item public.invoice_items%ROWTYPE;
BEGIN
  IF NOT public.is_admin() THEN
    RAISE EXCEPTION 'Only admins can synchronize invoice stock';
  END IF;

  SELECT *
  INTO v_invoice
  FROM public.invoices
  WHERE id = p_invoice_id
  FOR UPDATE;

  IF NOT FOUND OR v_invoice.product_id IS NOT NULL THEN
    RETURN;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM public.invoice_items WHERE invoice_id = p_invoice_id
  ) THEN
    RETURN;
  END IF;

  IF v_invoice.status IN ('paid', 'deposit') AND NOT v_invoice.items_stock_applied THEN
    FOR v_item IN
      SELECT *
      FROM public.invoice_items
      WHERE invoice_id = p_invoice_id
        AND product_id IS NOT NULL
    LOOP
      PERFORM set_config('app.stock_reason', 'sale', true);
      UPDATE public.products
      SET stock_quantity = greatest(0, coalesce(stock_quantity, 0) - v_item.quantity)
      WHERE id = v_item.product_id;
    END LOOP;

    UPDATE public.invoices
    SET items_stock_applied = true
    WHERE id = p_invoice_id;
  ELSIF v_invoice.status = 'cancelled' AND v_invoice.items_stock_applied THEN
    FOR v_item IN
      SELECT *
      FROM public.invoice_items
      WHERE invoice_id = p_invoice_id
        AND product_id IS NOT NULL
    LOOP
      PERFORM set_config('app.stock_reason', 'sale', true);
      UPDATE public.products
      SET stock_quantity = coalesce(stock_quantity, 0) + v_item.quantity
      WHERE id = v_item.product_id;
    END LOOP;

    UPDATE public.invoices
    SET items_stock_applied = false
    WHERE id = p_invoice_id;
  END IF;
END;
$$;

REVOKE ALL ON FUNCTION public.sync_invoice_items_stock(uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.sync_invoice_items_stock(uuid) TO authenticated;

CREATE OR REPLACE FUNCTION public.trigger_sync_invoice_items_stock()
RETURNS trigger
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
BEGIN
  PERFORM public.sync_invoice_items_stock(NEW.id);
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS "sync invoice item stock after status change" ON public.invoices;
CREATE TRIGGER "sync invoice item stock after status change"
  AFTER UPDATE OF status ON public.invoices
  FOR EACH ROW
  WHEN (OLD.status IS DISTINCT FROM NEW.status)
  EXECUTE FUNCTION public.trigger_sync_invoice_items_stock();

CREATE OR REPLACE FUNCTION public.create_multi_item_invoice(
  p_customer_name text,
  p_customer_phone text,
  p_customer_email text,
  p_items jsonb,
  p_discount numeric,
  p_deposit numeric,
  p_payment_method text,
  p_notes text,
  p_terms text
)
RETURNS public.invoices
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
DECLARE
  v_item jsonb;
  v_item_name text;
  v_product_id bigint;
  v_quantity integer;
  v_unit_price numeric;
  v_product_cost numeric;
  v_subtotal numeric := 0;
  v_unit_cost numeric := 0;
  v_total numeric;
  v_deposit numeric;
  v_status text;
  v_item_count integer;
  v_first_name text;
  v_snapshot_items jsonb := '[]'::jsonb;
  v_invoice public.invoices%ROWTYPE;
  v_position integer := 0;
BEGIN
  IF jsonb_typeof(p_items) IS DISTINCT FROM 'array' THEN
    RAISE EXCEPTION 'Items must be a JSON array';
  END IF;

  v_item_count := jsonb_array_length(p_items);
  IF v_item_count < 2 THEN
    RAISE EXCEPTION 'At least two items are required';
  END IF;

  IF p_discount IS NULL OR p_deposit IS NULL THEN
    RAISE EXCEPTION 'Discount and deposit are required';
  END IF;

  FOR v_item IN SELECT value FROM jsonb_array_elements(p_items) AS entries(value)
  LOOP
    v_item_name := nullif(btrim(v_item ->> 'name'), '');
    IF v_item_name IS NULL THEN
      RAISE EXCEPTION 'Each item must have a name';
    END IF;

    IF nullif(v_item ->> 'quantity', '') IS NULL THEN
      RAISE EXCEPTION 'Each item must have a quantity';
    END IF;
    v_quantity := (v_item ->> 'quantity')::integer;
    IF v_quantity <= 0 THEN
      RAISE EXCEPTION 'Item quantities must be positive';
    END IF;

    IF nullif(v_item ->> 'unit_price', '') IS NULL THEN
      RAISE EXCEPTION 'Each item must have a unit price';
    END IF;
    v_unit_price := (v_item ->> 'unit_price')::numeric;
    IF v_unit_price < 0 THEN
      RAISE EXCEPTION 'Item prices cannot be negative';
    END IF;

    v_product_id := nullif(v_item ->> 'product_id', '')::bigint;
    v_product_cost := 0;
    IF v_product_id IS NOT NULL THEN
      SELECT coalesce(p.cost_price, 0)
      INTO v_product_cost
      FROM public.products AS p
      WHERE p.id = v_product_id;
      IF NOT FOUND THEN
        RAISE EXCEPTION 'Product % does not exist', v_product_id;
      END IF;
    END IF;

    IF v_first_name IS NULL THEN
      v_first_name := v_item_name;
    END IF;
    v_subtotal := v_subtotal + v_quantity * v_unit_price;
    v_unit_cost := v_unit_cost + v_quantity * v_product_cost;
    v_snapshot_items := v_snapshot_items || jsonb_build_array(jsonb_build_object(
      'name', v_item_name,
      'brand', v_item ->> 'brand',
      'spec', v_item ->> 'spec',
      'imei', v_item ->> 'imei',
      'quantity', v_quantity,
      'unit_price', v_unit_price
    ));
  END LOOP;

  IF p_discount < 0 OR p_discount > v_subtotal THEN
    RAISE EXCEPTION 'Discount must be between zero and the subtotal';
  END IF;

  v_total := v_subtotal - p_discount;
  IF p_deposit < 0 OR p_deposit > v_total THEN
    RAISE EXCEPTION 'Deposit must be between zero and the invoice total';
  END IF;

  v_deposit := p_deposit;
  IF v_deposit = v_total THEN
    v_status := 'paid';
  ELSIF v_deposit > 0 THEN
    v_status := 'deposit';
  ELSE
    v_status := 'pending';
  END IF;

  INSERT INTO public.invoices (
    customer_name,
    customer_phone,
    customer_email,
    product_id,
    product_snapshot,
    quantity,
    unit_price,
    unit_cost,
    discount_amount,
    deposit_amount,
    status,
    payment_method,
    notes,
    terms_snapshot,
    paid_at
  )
  VALUES (
    p_customer_name,
    p_customer_phone,
    p_customer_email,
    NULL,
    jsonb_build_object(
      'multi', true,
      'item_count', v_item_count,
      'name', format('%s +%s more', v_first_name, v_item_count - 1),
      'items', v_snapshot_items
    ),
    1,
    v_subtotal,
    v_unit_cost,
    p_discount,
    v_deposit,
    v_status,
    p_payment_method,
    p_notes,
    p_terms,
    CASE WHEN v_status = 'paid' THEN now() ELSE NULL END
  )
  RETURNING * INTO v_invoice;

  FOR v_item IN SELECT value FROM jsonb_array_elements(p_items) AS entries(value)
  LOOP
    v_product_id := nullif(v_item ->> 'product_id', '')::bigint;
    INSERT INTO public.invoice_items (
      invoice_id,
      product_id,
      name,
      brand,
      spec,
      imei,
      quantity,
      unit_price,
      unit_cost,
      position
    )
    VALUES (
      v_invoice.id,
      v_product_id,
      btrim(v_item ->> 'name'),
      v_item ->> 'brand',
      v_item ->> 'spec',
      v_item ->> 'imei',
      (v_item ->> 'quantity')::integer,
      (v_item ->> 'unit_price')::numeric,
      CASE
        WHEN v_product_id IS NULL THEN NULL
        ELSE (SELECT p.cost_price FROM public.products AS p WHERE p.id = v_product_id)
      END,
      v_position
    );
    v_position := v_position + 1;
  END LOOP;

  PERFORM public.sync_invoice_items_stock(v_invoice.id);
  SELECT * INTO v_invoice FROM public.invoices WHERE id = v_invoice.id;
  RETURN v_invoice;
END;
$$;

REVOKE ALL ON FUNCTION public.create_multi_item_invoice(
  text, text, text, jsonb, numeric, numeric, text, text, text
) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.create_multi_item_invoice(
  text, text, text, jsonb, numeric, numeric, text, text, text
) TO authenticated;
