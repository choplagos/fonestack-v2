CREATE TABLE IF NOT EXISTS public.admin_rate_limit_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  scope text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS admin_rate_limit_events_user_scope_created_idx
  ON public.admin_rate_limit_events (user_id, scope, created_at);

ALTER TABLE public.admin_rate_limit_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.admin_rate_limit_events FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.consume_admin_rate_limit(p_scope text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_user_id uuid := auth.uid();
  v_limit integer;
  v_count integer;
  v_oldest timestamptz;
  v_retry_seconds integer;
BEGIN
  IF v_user_id IS NULL OR public.can_write() IS NOT TRUE THEN
    RAISE EXCEPTION 'Admin write access required' USING ERRCODE = '42501';
  END IF;

  IF p_scope = 'reply-draft' THEN
    v_limit := 30;
  ELSIF p_scope = 'market-price' THEN
    v_limit := 10;
  ELSE
    RAISE EXCEPTION 'Unknown rate-limit scope' USING ERRCODE = '22023';
  END IF;

  PERFORM pg_advisory_xact_lock(hashtextextended(v_user_id::text || ':' || p_scope, 0));

  DELETE FROM public.admin_rate_limit_events
  WHERE user_id = v_user_id
    AND scope = p_scope
    AND created_at <= now() - interval '1 hour';

  SELECT count(*)::integer, min(created_at)
  INTO v_count, v_oldest
  FROM public.admin_rate_limit_events
  WHERE user_id = v_user_id
    AND scope = p_scope
    AND created_at > now() - interval '1 hour';

  IF v_count >= v_limit THEN
    v_retry_seconds := greatest(1, ceil(extract(epoch FROM (v_oldest + interval '1 hour' - now())))::integer);
    RETURN jsonb_build_object('allowed', false, 'retry_after_seconds', v_retry_seconds);
  END IF;

  INSERT INTO public.admin_rate_limit_events (user_id, scope) VALUES (v_user_id, p_scope);
  RETURN jsonb_build_object('allowed', true, 'remaining', v_limit - v_count - 1);
END;
$$;

REVOKE ALL ON FUNCTION public.consume_admin_rate_limit(text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.consume_admin_rate_limit(text) TO authenticated;
