CREATE OR REPLACE FUNCTION public.receive_purchase(p_purchase_id bigint)
RETURNS void
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
DECLARE
  v_purchase public.purchases%ROWTYPE;
  v_item public.purchase_items%ROWTYPE;
BEGIN
  SELECT *
  INTO v_purchase
  FROM public.purchases
  WHERE id = p_purchase_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Purchase % does not exist', p_purchase_id;
  END IF;

  IF v_purchase.received_at IS NOT NULL THEN
    RAISE EXCEPTION 'Purchase % has already been received', p_purchase_id;
  END IF;

  FOR v_item IN
    SELECT *
    FROM public.purchase_items
    WHERE purchase_id = p_purchase_id
      AND product_id IS NOT NULL
  LOOP
    PERFORM set_config('app.stock_reason', 'purchase', true);
    UPDATE public.products
    SET stock_quantity = coalesce(stock_quantity, 0) + v_item.quantity,
        cost_price = v_item.unit_cost
    WHERE id = v_item.product_id;
  END LOOP;

  UPDATE public.purchases
  SET received_at = now(),
      total_cost = coalesce((
        SELECT sum(pi.quantity * pi.unit_cost)
        FROM public.purchase_items AS pi
        WHERE pi.purchase_id = p_purchase_id
      ), 0)
  WHERE id = p_purchase_id;
END;
$$;

REVOKE ALL ON FUNCTION public.receive_purchase(bigint) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.receive_purchase(bigint) TO authenticated;

