CREATE OR REPLACE FUNCTION public.log_stock_movement()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_old_qty integer;
  v_new_qty integer;
BEGIN
  IF TG_OP = 'INSERT' THEN
    v_old_qty := NULL;
    v_new_qty := NEW.stock_quantity;
  ELSE
    v_old_qty := OLD.stock_quantity;
    v_new_qty := NEW.stock_quantity;
    IF v_old_qty IS NOT DISTINCT FROM v_new_qty THEN
      RETURN NEW;
    END IF;
  END IF;

  INSERT INTO public.stock_movements (product_id, old_qty, new_qty, delta, reason)
  VALUES (
    NEW.id,
    v_old_qty,
    v_new_qty,
    coalesce(v_new_qty, 0) - coalesce(v_old_qty, 0),
    coalesce(nullif(current_setting('app.stock_reason', true), ''), 'manual_or_sale')
  );
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS "record product stock insert" ON public.products;
CREATE TRIGGER "record product stock insert"
  AFTER INSERT ON public.products
  FOR EACH ROW EXECUTE FUNCTION public.log_stock_movement();

DROP TRIGGER IF EXISTS "record product stock update" ON public.products;
CREATE TRIGGER "record product stock update"
  AFTER UPDATE OF stock_quantity ON public.products
  FOR EACH ROW WHEN (OLD.stock_quantity IS DISTINCT FROM NEW.stock_quantity)
  EXECUTE FUNCTION public.log_stock_movement();
